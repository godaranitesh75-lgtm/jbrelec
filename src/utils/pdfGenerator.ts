import { jsPDF } from 'jspdf';

export interface CartItem {
  item: string;
  qty: number;
}

export interface OrderDetails {
  name: string;
  phone: string;
  address: string;
  shopTime: string;
  shopImage?: string;
}

export function generateOrderPdf(cart: CartItem[], details: OrderDetails = {
  name: 'Not provided',
  phone: 'Not provided',
  address: 'Not provided',
  shopTime: 'Not provided',
}): File {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;
  let y = 20;

  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(13, 148, 136);
  doc.text('JBR ELECTRICAL', pageWidth / 2, y, { align: 'center' });
  y += 8;

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100);
  doc.text('Syed Jung Ln, Troop Bazaar, Koti, Hyderabad, Telangana 500001', pageWidth / 2, y, { align: 'center' });
  doc.text('Phone: 6377374179 | WhatsApp: 916377374179', pageWidth / 2, y + 6, { align: 'center' });
  y += 18;

  doc.setDrawColor(200, 200, 200);
  doc.line(margin, y, pageWidth - margin, y);
  y += 10;

  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 66, 58);
  doc.text('ORDER REQUEST', margin, y);
  y += 10;

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(80);
  const orderDate = new Date().toLocaleDateString('en-IN', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
  doc.text(`Order Date: ${orderDate}`, margin, y);
  doc.text(`Customer Phone: ${details.phone}`, pageWidth - margin, y, { align: 'right' });
  y += 12;

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 66, 58);
  doc.text('CUSTOMER DETAILS', margin, y);
  y += 7;
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(80);
  const customerDetails = [
    `Name: ${details.name}`,
    `Mobile: ${details.phone}`,
    `Address: ${details.address}`,
    `Shop opening time: ${details.shopTime}`,
  ];
  customerDetails.forEach((detail) => {
    const lines = doc.splitTextToSize(detail, contentWidth);
    doc.text(lines, margin, y);
    y += lines.length * 5;
  });
  y += 6;

  if (details.shopImage) {
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 66, 58);
    doc.text('SHOP CARD / BANNER', margin, y);
    y += 5;
    try {
      const imageType = details.shopImage.match(/^data:image\/(png|webp|jpeg|jpg)/i)?.[1]?.toUpperCase() ?? 'JPEG';
      const imageProperties = doc.getImageProperties(details.shopImage);
      const maxWidth = contentWidth;
      const maxHeight = 45;
      const scale = Math.min(maxWidth / imageProperties.width, maxHeight / imageProperties.height);
      const imageWidth = imageProperties.width * scale;
      const imageHeight = imageProperties.height * scale;
      doc.addImage(details.shopImage, imageType, margin, y, imageWidth, imageHeight);
      y += imageHeight + 10;
    } catch {
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(100);
      doc.text('Shop image could not be added.', margin, y + 5);
      y += 15;
    }
  }

  doc.setFillColor(245, 246, 250);
  doc.rect(margin, y, contentWidth, 10, 'F');
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(50);
  doc.text('#', margin + 4, y + 7);
  doc.text('Item Name', margin + 14, y + 7);
  doc.text('Qty', pageWidth - margin - 10, y + 7, { align: 'right' });
  y += 14;

  const totalItems = cart.reduce((sum, c) => sum + c.qty, 0);
  cart.forEach((c, index) => {
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(60);
    doc.text(`${index + 1}`, margin + 4, y + 6);
    const itemLines = doc.splitTextToSize(c.item, contentWidth - 38);
    doc.text(itemLines, margin + 14, y + 6);
    doc.text(`x${c.qty}`, pageWidth - margin - 10, y + 6, { align: 'right' });
    y += Math.max(10, itemLines.length * 5 + 5);
  });

  y += 5;
  doc.setDrawColor(200, 200, 200);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(13, 148, 136);
  doc.text(`Total Items: ${cart.length}`, margin, y);
  doc.text(`Total Quantity: ${totalItems}`, pageWidth - margin, y, { align: 'right' });
  y += 16;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(100);
  const note = 'Note: This is an order request. Please call to confirm availability and total amount before processing.';
  const splitNote = doc.splitTextToSize(note, contentWidth);
  doc.text(splitNote, margin, y);

  y += splitNote.length * 5 + 10;

  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text('Generated by JBR Electrical Website', pageWidth / 2, y + 20, { align: 'center' });

  const pdfBlob = doc.output('blob');
  return new File([pdfBlob], `JBR_Order_${new Date().toISOString().slice(0, 10)}.pdf`, { type: 'application/pdf' });
}
